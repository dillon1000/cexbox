"""Generate app/FontCoverage.cs: the list of characters the bundled terminal font has.

usage: python3 tools/fontranges.py app/Fonts/CascadiaMono.ttf > app/FontCoverage.cs

Run it again whenever the font file changes.
"""
import struct
import sys


def characters(path):
    d = open(path, "rb").read()
    count = struct.unpack_from(">H", d, 4)[0]
    tables = {d[12 + i * 16:16 + i * 16]: struct.unpack_from(">II", d, 20 + i * 16) for i in range(count)}
    off = tables[b"cmap"][0]
    cps = set()
    for i in range(struct.unpack_from(">H", d, off + 2)[0]):
        _, _, sub = struct.unpack_from(">HHI", d, off + 4 + i * 8)
        s = off + sub
        fmt = struct.unpack_from(">H", d, s)[0]
        if fmt == 12:
            for g in range(struct.unpack_from(">I", d, s + 12)[0]):
                a, b, _ = struct.unpack_from(">III", d, s + 16 + g * 12)
                cps.update(range(a, b + 1))
        elif fmt == 4:
            n = struct.unpack_from(">H", d, s + 6)[0] // 2
            ends = struct.unpack_from(">%dH" % n, d, s + 14)
            starts = struct.unpack_from(">%dH" % n, d, s + 16 + n * 2)
            deltas = struct.unpack_from(">%dh" % n, d, s + 16 + n * 4)
            ro = s + 16 + n * 6
            offsets = struct.unpack_from(">%dH" % n, d, ro)
            for k in range(n):
                for c in range(starts[k], ends[k] + 1):
                    if c == 0xFFFF:
                        continue
                    if offsets[k] == 0:
                        glyph = (c + deltas[k]) & 0xFFFF
                    else:
                        glyph = struct.unpack_from(">H", d, ro + k * 2 + offsets[k] + (c - starts[k]) * 2)[0]
                    if glyph:
                        cps.add(c)
    return sorted(cps)


def main(path):
    cps = characters(path)
    ranges = []
    for c in cps:
        if ranges and ranges[-1][1] == c - 1:
            ranges[-1][1] = c
        else:
            ranges.append([c, c])
    name = path.replace("\\", "/").split("/")[-1]
    print("// Generated by tools/fontranges.py from %s. Don't edit by hand." % name)
    print("namespace Cexbox")
    print("{")
    print("    // Which characters the bundled terminal font can draw.")
    print("    static partial class FontCoverage")
    print("    {")
    print("        // Inclusive start and end of each run of characters, in order.")
    print("        static readonly int[] Ranges =")
    print("        {")
    for i in range(0, len(ranges), 6):
        print("            " + " ".join("0x%04X, 0x%04X," % (a, b) for a, b in ranges[i:i + 6]))
    print("        };")
    print("    }")
    print("}")


if __name__ == "__main__":
    main(sys.argv[1])
